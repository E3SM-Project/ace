#!/usr/bin/env python
"""Emit the E30-E37 stage-3 coupled bundle (2026-09-19).

The first CFT block generated with all FOUR interface corrections, including
the momentum scaling found on 2026-09-19. Reserved decade: E30-E39, of which
E38/E39 are left free for a follow-up bundle.

Naming. The pre-existing CFT words (E18-E25) take A, B and C from the
ATMOSPHERE parent and W from the OCEAN parent, which is unambiguous only while
every atmosphere parent is W0. E34/E37 break that, so this block adds a `V`
slot for the atmosphere's loss weighting, immediately before `W`:

    A?_B??_C?_L?_O?_V?_W?_X?

E18-E25 keep their ids and are implicitly V0.

Design:
  * aerosol x CO2 2x2   E30 (A0C0)  E35 (A0C1)  E36 (A3C0)  E31 (A3C1)
  * ocean loss ladder   E30 (W0)    E32 (W1)    E33 (W2)
  * atmos loss ladder   E31 (V0)    E34 (V1)    E37 (V2)
  * seeds               E30 and E31 at S01/S02/S03, so the headline
                        A3C1-vs-baseline contrast has an error bar on both ends
"""

import pathlib
import subprocess
import sys

import yaml

D = pathlib.Path(__file__).resolve().parent
FT = pathlib.Path("/pscratch/sd/m/mahf708/aug26-ft")
RUNS = D / "runs"
MAX_EPOCHS = 25  # E23 plateaued by ~epoch 9; 50 was ~3 walltime segments
NODES = 4  # B16: 16 ranks, local batch 1

ATM = {
    "E01": "E01-FT.aug26.atm.A0_B16_C0_L0_O5_W0_X0.S{s}",
    "E02": "E02-FT.aug26.atm.A0_B16_C1_L0_O5_W0_X0.S{s}",
    "E05": "E05-FT.aug26.atm.A3_B16_C1_L0_O5_W0_X0.S{s}",
    "E06": "E06-FT.aug26.atm.A3_B16_C0_L0_O5_W0_X0.S{s}",
    "E07": "E07-FT.aug26.atm.A3_B16_C1_L0_O5_W1_X0.S{s}",
    "E08": "E08-FT.aug26.atm.A3_B16_C1_L0_O5_W2_X0.S{s}",
}
OCN = {
    "E11": "E11-FT.aug26.ocn.A0_B16_C0_L0_O5_W0_X0.S{s}",
    "E12": "E12-FT.aug26.ocn.A0_B16_C0_L0_O5_W1_X0.S{s}",
    "E13": "E13-FT.aug26.ocn.A0_B16_C0_L0_O5_W2_X0.S{s}",
}

# exp, seeds, atm family, ocn family, factor word (minus the seed), why
ARMS = [
    ("E30", ["01", "02", "03"], "E01", "E11", "A0_B16_C0_L0_O5_V0_W0_X0",
     "baseline, three seeds"),
    ("E31", ["01", "02", "03"], "E05", "E11", "A3_B16_C1_L0_O5_V0_W0_X0",
     "aerosol inputs+outputs and CO2, three seeds"),
    ("E32", ["01"], "E01", "E12", "A0_B16_C0_L0_O5_V0_W1_X0",
     "ocean interface-upweighted loss"),
    ("E33", ["01"], "E01", "E13", "A0_B16_C0_L0_O5_V0_W2_X0",
     "ocean away-from-surface dilution"),
    ("E34", ["01"], "E07", "E11", "A3_B16_C1_L0_O5_V1_W0_X0",
     "atmosphere flux-upweighted loss (vs E31)"),
    ("E35", ["01"], "E02", "E11", "A0_B16_C1_L0_O5_V0_W0_X0",
     "CO2 only, the A0C1 cell"),
    ("E36", ["01"], "E06", "E11", "A3_B16_C0_L0_O5_V0_W0_X0",
     "aerosol only, the A3C0 cell"),
    ("E37", ["01"], "E08", "E11", "A3_B16_C1_L0_O5_V2_W0_X0",
     "atmosphere away-from-surface dilution (vs E31)"),
]

# The ocean families other than E11 are single-seed; pin them to S01.
SINGLE_SEED_OCN = {"E12", "E13"}


def parent(table, family, seed, single_seed=()):
    name = table[family].format(s="01" if family in single_seed else seed)
    p = FT / name
    ckpt = p / "training_checkpoints" / "best_inference_ckpt.tar"
    if not ckpt.exists():
        sys.exit(f"missing parent checkpoint: {ckpt}")
    return name, p / "config.yaml", ckpt


def main():
    written = []
    for exp, seeds, atm_fam, ocn_fam, word, why in ARMS:
        for seed in seeds:
            runid = f"{exp}-CFT.aug26.cpl.{word}.S{seed}"
            atm_name, atm_cfg, atm_ckpt = parent(ATM, atm_fam, seed)
            ocn_name, ocn_cfg, ocn_ckpt = parent(
                OCN, ocn_fam, seed, SINGLE_SEED_OCN
            )
            out = RUNS / f"{runid}.yaml"
            subprocess.run(
                [sys.executable, str(D / "make_cpl_config.py"),
                 "--atm-config", str(atm_cfg), "--ocn-config", str(ocn_cfg),
                 "--atm-ckpt", str(atm_ckpt), "--ocn-ckpt", str(ocn_ckpt),
                 "--nodes", str(NODES), "--out", str(out)],
                check=True, stdout=subprocess.DEVNULL,
            )
            cfg = yaml.safe_load(out.read_text())
            cfg["max_epochs"] = MAX_EPOCHS
            out.write_text(yaml.safe_dump(cfg, sort_keys=False))

            tags = ",".join(
                ["cft", "stage3", "aug26", exp, "cpl", *word.split("_"),
                 f"S{seed}", "momentum-fix", "e3x-bundle"]
            )
            (RUNS / f"{runid}.env").write_text(
                f"# generated by make_e3x_cft.py -- stage-3 coupled, E3x bundle "
                f"(2026-09-19)\n"
                f"# {why}\n"
                f"# atm parent {atm_name}\n"
                f"# ocn parent {ocn_name}\n"
                f"# All four interface corrections: open-water flux scaling, the\n"
                f"# static atmosphere_flux_fraction, interpolate_weight_power, and\n"
                f"# the momentum static_flux_scaling added 2026-09-19.\n"
                f"FME_NODES={NODES}\n"
                f"FME_RANKS={NODES * 4}\n"
                f"FME_PRIORITY=1\n"
                f"WANDB_NAME={runid}\n"
                f"WANDB_RUN_GROUP=aug26.cpl.{exp}-CFT\n"
                f"WANDB_JOB_TYPE={word}_CFT\n"
                f"WANDB_TAGS={tags}\n"
                f'WANDB_NOTES="stage-3 {why}: {atm_name} (atm) x {ocn_name} '
                f'(ocn) | {NODES} nodes, {NODES * 4} ranks, {MAX_EPOCHS} epochs, '
                f'all four interface fixes"\n'
            )
            written.append(runid)
    print(f"wrote {len(written)} runs:")
    for r in written:
        print(" ", r)


if __name__ == "__main__":
    main()
