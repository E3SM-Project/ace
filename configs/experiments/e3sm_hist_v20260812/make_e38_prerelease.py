#!/usr/bin/env python
"""E38-CFT: the prerelease pair coupled.

E30-E37 is a factorial around the baseline, so it never pairs the two best
components: E31 takes the best atmosphere with the baseline ocean (E11-FT W0)
and E32 takes the best ocean with the C0 atmosphere. This arm is the pair a
prerelease would actually ship together --

    atmosphere  E05-FT A3_B16_C1 S03   0.189 K in sample, 0.137 K in 2040
    ocean       E12-FT B16 W1 S01      0.086 K in sample, 0.199 K in 2040

-- coupled with all four interface fixes. Seeds differ between realms because
the best checkpoint of each realm was selected independently; the run id takes
the atmosphere's seed, following A/B/C, and the ocean's is recorded here and in
the .env.
"""
import pathlib, subprocess, sys, yaml

D = pathlib.Path(__file__).resolve().parent
FT = pathlib.Path("/pscratch/sd/m/mahf708/aug26-ft")
ATM = "E05-FT.aug26.atm.A3_B16_C1_L0_O5_W0_X0.S03"
OCN = "E12-FT.aug26.ocn.A0_B16_C0_L0_O5_W1_X0.S01"
WORD = "A3_B16_C1_L0_O5_V0_W1_X0"   # A/B/C/V from the atmosphere, W from the ocean
RUNID = f"E38-CFT.aug26.cpl.{WORD}.S03"
NODES, MAX_EPOCHS = 4, 25

for p in (FT / ATM, FT / OCN):
    ck = p / "training_checkpoints" / "best_inference_ckpt.tar"
    if not ck.exists():
        sys.exit(f"missing {ck}")

out = D / "runs" / f"{RUNID}.yaml"
subprocess.run([sys.executable, str(D / "make_cpl_config.py"),
                "--atm-config", str(FT / ATM / "config.yaml"),
                "--ocn-config", str(FT / OCN / "config.yaml"),
                "--atm-ckpt", str(FT / ATM / "training_checkpoints" / "best_inference_ckpt.tar"),
                "--ocn-ckpt", str(FT / OCN / "training_checkpoints" / "best_inference_ckpt.tar"),
                "--nodes", str(NODES), "--out", str(out)],
               check=True, stdout=subprocess.DEVNULL)
cfg = yaml.safe_load(out.read_text())
cfg["max_epochs"] = MAX_EPOCHS
out.write_text(yaml.safe_dump(cfg, sort_keys=False))

tags = ",".join(["cft", "stage3", "aug26", "E38", "cpl", *WORD.split("_"),
                 "S03", "momentum-fix", "prerelease-pair"])
(D / "runs" / f"{RUNID}.env").write_text(
    f"# generated by make_e38_prerelease.py (2026-09-20)\n"
    f"# The two prerelease component checkpoints, coupled.\n"
    f"# atm parent {ATM}   (best stage-2 atmosphere: 0.189 K held out, 0.137 K in 2040)\n"
    f"# ocn parent {OCN}   (best stage-2 ocean: 0.086 K held out, 0.199 K in 2040)\n"
    f"# Seeds differ by realm: each realm's best checkpoint was chosen on its own\n"
    f"# merit. The run id carries the atmosphere's seed, as A/B/C already do.\n"
    f"FME_NODES={NODES}\nFME_RANKS={NODES*4}\nFME_PRIORITY=1\n"
    f"WANDB_NAME={RUNID}\nWANDB_RUN_GROUP=aug26.cpl.E38-CFT\n"
    f"WANDB_JOB_TYPE={WORD}_CFT\nWANDB_TAGS={tags}\n"
    f'WANDB_NOTES="stage-3 prerelease pair: {ATM} (atm) x {OCN} (ocn) | '
    f'{NODES} nodes, {MAX_EPOCHS} epochs, all four interface fixes"\n')
print(RUNID)
