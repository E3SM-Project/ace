"""Write runs/<name>.yaml: config-train-hr.yaml cut down for a systems test.

    python scripts/make_smoke.py NAME --dp N [--htf F] [--lr-stats]

Short train/validation windows, a 12-step inline inference on N initial
conditions, checkpoints every 20 batches. --lr-stats swaps in the LR
historical campaign's normalization (same variable names) for runs that
only test the plumbing while the HR stats are being computed.
"""

import argparse
import copy
import os

import yaml

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LR_STATS = (
    "/global/cfs/cdirs/e3smdata/emulator/SamudrACE-E3SMv3/historical/"
    "stats-2026-08-13/train-only/atmosphere"
)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("name")
    p.add_argument("--dp", type=int, required=True, help="data-parallel size")
    p.add_argument("--htf", type=float, default=None)
    p.add_argument("--lr-stats", action="store_true")
    p.add_argument("--train-stop", default="0001-03-01T00:00:00")
    p.add_argument("--workers", type=int, default=4)
    a = p.parse_args()
    c = yaml.safe_load(open(os.path.join(HERE, "config-train-hr.yaml")))
    c = copy.deepcopy(c)
    c["max_epochs"] = 1
    c["log_train_every_n_batches"] = 5
    c["checkpoint_every_n_batches"] = 20
    c["train_loader"]["batch_size"] = a.dp
    c["train_loader"]["num_data_workers"] = a.workers
    c["train_loader"]["dataset"]["subset"]["stop_time"] = a.train_stop
    v = c["validation"]["loader"]
    v["batch_size"] = a.dp
    v["dataset"]["subset"] = {
        "start_time": "0014-01-01T00:00:00",
        "stop_time": "0014-01-08T00:00:00",
    }
    inf = c["inference"][0]
    inf["epochs"] = {"start": 0, "step": 1}
    inf["n_forward_steps"] = 12
    inf["forward_steps_in_memory"] = 4
    inf["loader"]["start_indices"]["times"] = inf["loader"]["start_indices"]["times"][
        : a.dp
    ]
    builder = c["stepper"]["step"]["config"]["builder"]["config"]
    if a.htf is not None:
        builder["hard_thresholding_fraction"] = a.htf
    if a.lr_stats:
        norm = c["stepper"]["step"]["config"]["normalization"]
        norm["network"]["global_means_path"] = f"{LR_STATS}/centering.nc"
        norm["network"]["global_stds_path"] = f"{LR_STATS}/scaling-full-field.nc"
        norm["residual"]["global_means_path"] = f"{LR_STATS}/centering.nc"
        norm["residual"]["global_stds_path"] = f"{LR_STATS}/scaling-residual.nc"
    os.makedirs(os.path.join(HERE, "runs"), exist_ok=True)
    out = os.path.join(HERE, "runs", f"{a.name}.yaml")
    with open(out, "w") as f:
        f.write(f"# GENERATED by scripts/make_smoke.py {a.name} -- do not edit\n")
        yaml.safe_dump(c, f, sort_keys=False)
    print(out)


if __name__ == "__main__":
    main()
